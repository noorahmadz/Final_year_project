export const createDefaultGroups = () => ({
  groupA: [],
  groupB: [],
});

export const getTournamentMatches = (tournament) => {
  const groupMatches = Array.isArray(tournament?.groupMatches)
    ? tournament.groupMatches.map(adaptMatch).filter(Boolean)
    : [];
  const knockoutMatches = Array.isArray(tournament?.knockoutMatches)
    ? tournament.knockoutMatches.map(adaptMatch).filter(Boolean)
    : [];

  return {
    groupMatches,
    knockoutMatches,
    allMatches: [...groupMatches, ...knockoutMatches],
  };
};

export const assignTeamToGroup = (groups, team) => {
  const groupACount = groups.groupA.length;
  const groupBCount = groups.groupB.length;
  if (groupACount <= groupBCount) {
    return { ...groups, groupA: [...groups.groupA, team] };
  }
  return { ...groups, groupB: [...groups.groupB, team] };
};

