export const calculateStandings = (teams, matches, groupName) => {
  const groupMatches = matches.filter(
    (match) => match.group === groupName && match.status === "completed",
  );
  const standings = teams.map((team) => {
    const teamMatches = groupMatches.filter(
      (match) => match.team1Id === team.id || match.team2Id === team.id,
    );
    let points = 0;
    let wins = 0;
    let draws = 0;
    let losses = 0;
    let goalsFor = 0;
    let goalsAgainst = 0;
    const played = teamMatches.length;

    teamMatches.forEach((match) => {
      const isTeam1 = match.team1Id === team.id;
      const score1 = isTeam1 ? match.score1 : match.score2;
      const score2 = isTeam1 ? match.score2 : match.score1;
      goalsFor += score1 || 0;
      goalsAgainst += score2 || 0;
      if (match.isDraw) {
        draws += 1;
        points += 1;
      } else if (match.winner === team.id) {
        wins += 1;
        points += 3;
      } else {
        losses += 1;
      }
    });

    return {
      teamId: team.id,
      teamName: team.captainName,
      played,
      wins,
      draws,
      losses,
      goalsFor,
      goalsAgainst,
      goalDifference: goalsFor - goalsAgainst,
      points,
    };
  });

  return standings.sort((a, b) => {
    if (b.points !== a.points) {
      return b.points - a.points;
    }
    if (b.goalDifference !== a.goalDifference) {
      return b.goalDifference - a.goalDifference;
    }
    return b.goalsFor - a.goalsFor;
  });
};

export const getTopTeams = (standings, count = 2) => standings.slice(0, count);

