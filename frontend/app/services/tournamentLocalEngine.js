export const generateGroupMatches = (teams, groupName, existingMatches = []) => {
  const matches = [];
  const existingIds = existingMatches.map(
    (match) => `${match.team1Id}_${match.team2Id}`,
  );
  for (let i = 0; i < teams.length; i += 1) {
    for (let j = i + 1; j < teams.length; j += 1) {
      const matchKey1 = `${teams[i].id}_${teams[j].id}`;
      const matchKey2 = `${teams[j].id}_${teams[i].id}`;
      if (existingIds.includes(matchKey1) || existingIds.includes(matchKey2)) {
        continue;
      }
      matches.push({
        id: `match_${groupName}_${Date.now()}_${i}_${j}`,
        team1Id: teams[i].id,
        team2Id: teams[j].id,
        team1Name: teams[i].captainName,
        team2Name: teams[j].captainName,
        group: groupName,
        status: "scheduled",
        score1: null,
        score2: null,
        winner: null,
        loser: null,
        isDraw: false,
        round: "Group Stage",
        isAutoGenerated: true,
      });
    }
  }
  return matches;
};

