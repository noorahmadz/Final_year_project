export const generateFinalRanking = (
  groupATeams,
  groupBTeams,
  groupAStandings,
  groupBStandings,
  knockoutMatches,
  options = {},
) => {
  const variant = options.variant || "list";
  const ranking = [];
  const completedKnockout = knockoutMatches.filter(
    (match) => match.status === "completed",
  );

  if (variant === "owner") {
    const championMatch = completedKnockout.find(
      (match) => match.round === "Final" || match.round === "Match 1",
    );
    const champion = championMatch?.winner || null;
    const challengeMatch = completedKnockout.find(
      (match) =>
        match.round === "Challenge Match" || match.round === "Third Place",
    );
    const runnerUp = challengeMatch?.winner || championMatch?.loser || null;
    const semiFinalMatch = completedKnockout.find(
      (match) =>
        match.round === "Semi-Final" ||
        match.round === "Semi-Final 1" ||
        match.round === "Semi-Final 2" ||
        match.round === "Match 2",
    );
    const semiFinalWinner = semiFinalMatch?.winner || null;
    const semiFinalLoser = semiFinalMatch?.loser || null;
    const thirdPlace = challengeMatch?.loser || semiFinalWinner || null;
    const allTeams = [...(groupATeams || []), ...(groupBTeams || [])];

    for (let i = 0; i < allTeams.length; i += 1) {
      const team = allTeams[i];
      const isChampion = champion === team.id;
      const isRunnerUp = runnerUp === team.id;
      const isThirdPlace = thirdPlace === team.id;
      const isSemiFinalWinner = semiFinalWinner === team.id;
      const isSemiFinalLoser = semiFinalLoser === team.id;

      let position;
      if (isChampion) position = 1;
      else if (isRunnerUp) position = 2;
      else if (isThirdPlace) position = 3;
      else if (isSemiFinalWinner) position = 4;
      else if (isSemiFinalLoser) position = 5;
      else {
        const groupAStanding = groupAStandings.find(
          (standing) => standing.teamId === team.id,
        );
        const groupBStanding = groupBStandings.find(
          (standing) => standing.teamId === team.id,
        );
        if (groupAStanding) position = 6 + groupAStandings.indexOf(groupAStanding);
        else if (groupBStanding) position = 6 + groupBStandings.indexOf(groupBStanding);
        else position = 6 + i;
      }

      ranking.push({
        position,
        teamId: team.id,
        teamName: team.captainName,
      });
    }

    return ranking.sort((a, b) => a.position - b.position);
  }

  const champion = completedKnockout.find(
    (match) => match.knockoutPosition === 1,
  )?.winner;
  const runnerUp = completedKnockout.find(
    (match) => match.knockoutPosition === 1,
  )?.loser;
  const semiFinalWinner = completedKnockout.find(
    (match) => match.knockoutPosition === 2,
  )?.winner;
  const semiFinalLoser = completedKnockout.find(
    (match) => match.knockoutPosition === 2,
  )?.loser;
  const allTeams = [...(groupATeams || []), ...(groupBTeams || [])];

  for (let i = 0; i < allTeams.length; i += 1) {
    const team = allTeams[i];
    const isChampion = champion === team.id;
    const isRunnerUp = runnerUp === team.id;
    const isSemiFinalWinner = semiFinalWinner === team.id;
    const isSemiFinalLoser = semiFinalLoser === team.id;

    let position;
    if (isChampion) position = 1;
    else if (isRunnerUp) position = 2;
    else if (isSemiFinalWinner) position = 3;
    else if (isSemiFinalLoser) position = 4;
    else {
      const groupAStanding = groupAStandings.find(
        (standing) => standing.teamId === team.id,
      );
      const groupBStanding = groupBStandings.find(
        (standing) => standing.teamId === team.id,
      );
      if (groupAStanding) position = 5 + groupAStandings.indexOf(groupAStanding);
      else if (groupBStanding) position = 5 + groupBStandings.indexOf(groupBStanding);
      else position = 5 + i;
    }

    ranking.push({
      position,
      teamId: team.id,
      teamName: team.captainName,
    });
  }

  return ranking.sort((a, b) => a.position - b.position);
};

