export const generateKnockoutMatches = (
  groupAQualifiers,
  groupBQualifiers,
  existingKnockoutMatches = [],
  options = {},
) => {
  if (groupAQualifiers.length < 2 || groupBQualifiers.length < 2) {
    return existingKnockoutMatches;
  }

  const variant = options.variant || "list";
  const newMatches = [];
  const existingIds = existingKnockoutMatches.map((match) => match.id);

  if (variant === "owner") {
    const match1Id = "knockout_final";
    if (!existingIds.includes(match1Id)) {
      newMatches.push({
        id: match1Id,
        team1Id: groupAQualifiers[0].teamId,
        team2Id: groupBQualifiers[0].teamId,
        team1Name: groupAQualifiers[0].teamName,
        team2Name: groupBQualifiers[0].teamName,
        round: "Final",
        knockoutPosition: 1,
        status: "scheduled",
        winner: null,
        loser: null,
        isDraw: false,
      });
    }

    const match2Id = "knockout_semifinal";
    if (!existingIds.includes(match2Id)) {
      newMatches.push({
        id: match2Id,
        team1Id: groupAQualifiers[1].teamId,
        team2Id: groupBQualifiers[1].teamId,
        team1Name: groupAQualifiers[1].teamName,
        team2Name: groupBQualifiers[1].teamName,
        round: "Semi-Final",
        knockoutPosition: 2,
        status: "scheduled",
        winner: null,
        loser: null,
        isDraw: false,
      });
    }

    const match3Id = "knockout_challenge";
    if (!existingIds.includes(match3Id)) {
      newMatches.push({
        id: match3Id,
        team1Id: null,
        team2Id: null,
        team1Name: "TBD",
        team2Name: "TBD",
        round: "Challenge Match",
        knockoutPosition: 3,
        status: "scheduled",
        dependsOn: [match2Id, match1Id],
        winner: null,
        loser: null,
        isDraw: false,
      });
    }

    return [...existingKnockoutMatches, ...newMatches];
  }

  const match1Id = "knockout_final";
  if (!existingIds.includes(match1Id)) {
    newMatches.push({
      id: match1Id,
      team1Id: groupAQualifiers[0].teamId,
      team2Id: groupBQualifiers[0].teamId,
      team1Name: groupAQualifiers[0].teamName,
      team2Name: groupBQualifiers[0].teamName,
      round: "Final (A1 vs B1)",
      knockoutPosition: 1,
      status: "scheduled",
      winner: null,
      loser: null,
      isDraw: false,
    });
  }

  const match2Id = "knockout_semifinal";
  if (!existingIds.includes(match2Id)) {
    newMatches.push({
      id: match2Id,
      team1Id: groupAQualifiers[1].teamId,
      team2Id: groupBQualifiers[1].teamId,
      team1Name: groupAQualifiers[1].teamName,
      team2Name: groupBQualifiers[1].teamName,
      round: "Semi-Final (A2 vs B2)",
      knockoutPosition: 2,
      status: "scheduled",
      winner: null,
      loser: null,
      isDraw: false,
    });
  }

  const match3Id = "knockout_thirdplace";
  if (!existingIds.includes(match3Id)) {
    newMatches.push({
      id: match3Id,
      team1Id: null,
      team2Id: null,
      team1Name: "Winner Semi-Final",
      team2Name: "Final Loser",
      round: "Third Place Playoff",
      knockoutPosition: 3,
      status: "pending",
      dependsOn: [match2Id, match1Id],
      winner: null,
      loser: null,
      isDraw: false,
    });
  }

  return [...existingKnockoutMatches, ...newMatches];
};

